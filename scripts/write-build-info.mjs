#!/usr/bin/env node
/**
 * Writes src/lib/build-info.ts with the short git SHA + a local build
 * timestamp at the moment the script runs. The Header reads it and
 * displays a small mono pill next to the logo so Beto can eyeball
 * whether a deploy actually replaced the previous version.
 *
 * Runs as part of the prebuild-mocks chain — every dev / build / deploy
 * regenerates the file.
 */
import { execSync } from "node:child_process";
import { writeFileSync, mkdirSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const root = join(here, "..");
const outFile = join(root, "src/lib/build-info.ts");

let sha = "dev";
try {
  sha = execSync("git rev-parse --short HEAD", { cwd: root }).toString().trim() || "dev";
} catch {
  // not a git checkout, or git unavailable
}

const now = new Date();
const stamp =
  `${String(now.getDate()).padStart(2, "0")}.` +
  `${String(now.getMonth() + 1).padStart(2, "0")} ` +
  `${String(now.getHours()).padStart(2, "0")}:` +
  `${String(now.getMinutes()).padStart(2, "0")}`;

const out = `// AUTO-GENERATED by scripts/write-build-info.mjs — DO NOT EDIT BY HAND.
// Refreshed every dev / build / deploy.

export const BUILD_SHA = ${JSON.stringify(sha)};
export const BUILD_TIME = ${JSON.stringify(stamp)};
`;

mkdirSync(dirname(outFile), { recursive: true });
writeFileSync(outFile, out);

console.log(`✓ build-info: ${sha} · ${stamp}`);
