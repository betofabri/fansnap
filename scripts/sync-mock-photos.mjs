#!/usr/bin/env node
/**
 * Scans public/mock/ and emits src/lib/photo-manifest.ts so mock.ts can pick
 * up files dropped into the folders without renaming or code changes.
 *
 * Structure (post-Fatia 1.6):
 *   public/mock/events/<code>/NN.jpg   →  per-event photo set
 *                                          first file = cover for tile/hero
 *                                          rest = gallery photos for that event
 *   public/mock/events/<code>.jpg      →  legacy single-cover (still supported)
 *   public/mock/photos/*.jpg           →  legacy shared gallery pool (fallback)
 *
 * Runs automatically before dev / build / preview / deploy.
 */
import { readdirSync, statSync, writeFileSync, mkdirSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const root = join(here, "..");
const eventsDir = join(root, "public/mock/events");
const photosDir = join(root, "public/mock/photos");
const outFile  = join(root, "src/lib/photo-manifest.ts");

const IMG_RX = /\.(jpe?g|png|webp|avif|gif)$/i;

const safeRead = (dir) => {
  try { return readdirSync(dir); } catch { return []; }
};

const safeStat = (p) => {
  try { return statSync(p); } catch { return null; }
};

const sortAlpha = (arr) => [...arr].sort((a, b) => a.localeCompare(b, "en", { numeric: true }));

// ── per-event folders: public/mock/events/<code>/NN.jpg ─────────────────────
const eventPhotos = {};
for (const name of safeRead(eventsDir)) {
  const p = join(eventsDir, name);
  const st = safeStat(p);
  if (!st?.isDirectory()) continue;
  const photos = safeRead(p).filter((n) => IMG_RX.test(n));
  if (photos.length > 0) {
    eventPhotos[name.toLowerCase()] = sortAlpha(photos);
  }
}

// ── legacy single-cover: public/mock/events/<code>.<ext> ────────────────────
const eventCovers = {};
for (const fn of safeRead(eventsDir)) {
  if (!IMG_RX.test(fn)) continue;
  const code = fn.replace(IMG_RX, "").toLowerCase();
  if (!eventPhotos[code]) eventCovers[code] = fn;
}

// ── legacy shared gallery pool: public/mock/photos/*.<ext> ──────────────────
const sharedPhotos = sortAlpha(
  safeRead(photosDir).filter((n) => IMG_RX.test(n))
);

const out = `// AUTO-GENERATED by scripts/sync-mock-photos.mjs — DO NOT EDIT BY HAND.
// Refresh with \`npm run sync-mocks\` (auto-runs on dev/build/deploy).

/** Per-event photo sets: public/mock/events/<code>/NN.jpg.
 *  First entry (alphabetical) is treated as the cover. Rest = gallery. */
export const EVENT_PHOTOS: Record<string, readonly string[]> = ${JSON.stringify(eventPhotos, null, 2)};

/** Legacy single-cover files: public/mock/events/<code>.<ext>. */
export const EVENT_COVERS: Record<string, string> = ${JSON.stringify(eventCovers, null, 2)};

/** Legacy shared gallery pool: public/mock/photos/*.<ext>. */
export const PHOTO_FILES: readonly string[] = ${JSON.stringify(sharedPhotos, null, 2)};
`;

mkdirSync(dirname(outFile), { recursive: true });
writeFileSync(outFile, out);

const eventCount = Object.keys(eventPhotos).length;
const totalEventPhotos = Object.values(eventPhotos).reduce((n, a) => n + a.length, 0);
console.log(
  `✓ photo-manifest synced: ${eventCount} events with ${totalEventPhotos} photos total, ` +
  `${Object.keys(eventCovers).length} legacy covers, ${sharedPhotos.length} shared pool`,
);
