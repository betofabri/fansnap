#!/usr/bin/env node
/**
 * Scans public/mock/photos/ and public/mock/events/ and emits a manifest
 * that mock.ts imports. Lets Beto drop any number of files with any names
 * into those folders and have the app pick them up automatically.
 *
 * Runs automatically before `npm run dev`, `npm run build`, `npm run deploy`.
 * You can also run it manually:  npm run sync-mocks
 */
import { readdirSync, writeFileSync, mkdirSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const root = join(here, "..");
const photosDir = join(root, "public/mock/photos");
const eventsDir = join(root, "public/mock/events");
const outFile  = join(root, "src/lib/photo-manifest.ts");

const IMG_RX = /\.(jpe?g|png|webp|avif|gif)$/i;

const safeList = (dir) => {
  try {
    return readdirSync(dir).filter((n) => IMG_RX.test(n)).sort();
  } catch {
    return [];
  }
};

const photoFiles = safeList(photosDir);

// For events, we expect filenames like `ccxp-26.jpg` — map the bare event
// code (lowercase) to the actual filename so the gallery can find it
// regardless of the extension (.jpg / .png / .webp).
const eventFiles = {};
for (const fn of safeList(eventsDir)) {
  const code = fn.replace(IMG_RX, "").toLowerCase();
  eventFiles[code] = fn;
}

const out = `// AUTO-GENERATED by scripts/sync-mock-photos.mjs — DO NOT EDIT BY HAND.
// Drop your photos in:
//   public/mock/photos/   (any names — used in alphabetical order)
//   public/mock/events/<event-code>.{jpg,png,webp,…}  (one per event)
// Then run \`npm run sync-mocks\` (auto-runs on dev/build/deploy).

export const PHOTO_FILES = ${JSON.stringify(photoFiles, null, 2)} as const;

export const EVENT_FILES: Record<string, string> = ${JSON.stringify(eventFiles, null, 2)};
`;

mkdirSync(dirname(outFile), { recursive: true });
writeFileSync(outFile, out);

console.log(
  `✓ photo-manifest synced: ${photoFiles.length} photos, ${Object.keys(eventFiles).length} event covers`,
);
